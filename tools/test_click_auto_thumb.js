const { chromium } = require('playwright-core');

const PROFILE_DIR = 'C:\\Users\\badiu\\.gemini\\antigravity\\scratch\\chrome_aistudio_profile_3';
const CHROME_PATH = 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';

(async () => {
  const ctx = await chromium.launchPersistentContext(PROFILE_DIR, {
    headless: false,
    executablePath: CHROME_PATH,
    args: ['--start-maximized', '--disable-blink-features=AutomationControlled'],
    viewport: null
  });
  const page = ctx.pages()[0] || await ctx.newPage();
  await page.goto('https://studio.youtube.com/video/Kuc5FRoYJW0/edit', { waitUntil: 'domcontentloaded', timeout: 30000 });
  await page.waitForTimeout(4000);

  // Scroll
  await page.evaluate(() => {
    const m = document.querySelector('main#main');
    if (m) m.scrollTop = 500;
  });
  await page.waitForTimeout(1000);

  const autoEditor = page.locator('ytcp-video-autogenerated-thumbnails-editor button#select-button').first();
  console.log('Auto editor button exists:', await autoEditor.count());
  if (await autoEditor.isVisible()) {
    console.log('Clicking auto editor button...');
    await autoEditor.click();
    await page.waitForTimeout(3000);
    await page.screenshot({ path: 'tools/after_auto_editor_click.png' });
    console.log('Saved tools/after_auto_editor_click.png');
  }

  // Check if any dialog or frame picker popped up
  const dialogs = await page.locator('ytcp-dialog, ytcp-modal-dialog, iron-overlay-backdrop').count();
  console.log('Dialogs count:', dialogs);

  await ctx.close();
})();
